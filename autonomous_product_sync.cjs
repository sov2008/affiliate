function log(msg) {
  const line = `[${new Date().toISOString()}] [PRODUCT-SYNC] ${msg}`;
  console.log(line);
  try {
    fs.appendFileSync(SYNC_LOG, line + '\n');
  } catch {}
}

function queryGraphQL(query) {
  return new Promise((resolve, reject) => {
    const postData = JSON.stringify({ query });
    const req = https.request({
      hostname: 'ads.api.cj.com',
      path: '/query',
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${CJ_TOKEN}`,
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(postData),
        'User-Agent': 'PromoRadar-Product-Ingestor/1.0'
      }
    }, (res) => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        try {
          resolve(JSON.parse(data));
        } catch (e) {
          reject(new Error(`Failed to parse GraphQL response: ${data.slice(0, 200)}`));
        }
      });
    });
    req.on('error', reject);
    req.write(postData);
    req.end();
  });
}

function cleanDescription(desc) {
  if (!desc) return '';
  return desc
    .replace(/<[^>]*>/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 180) + '...';
}

async function fetchProductsForPartner(partnerId, limit = 6) {
  const query = `
    query getProducts {
      products(companyId: "${COMPANY_ID}", partnerIds: ["${partnerId}"], limit: ${limit}) {
        totalCount
        resultList {
          id
          title
          description
          price {
            amount
            currency
          }
          imageLink
          link
          brand
        }
      }
    }
  `;

  const res = await queryGraphQL(query);
  if (res.errors && res.errors.length > 0) {
    throw new Error(res.errors[0].message);
  }

  return res.data?.products?.resultList || [];
}

async function syncAllProducts() {
  log('Starting Autonomous Product Catalog Sync Cycle...');
  const catalog = {};

  for (const partner of TARGET_PARTNERS) {
    try {
      log(`Querying products for ${partner.name} (ID: ${partner.id})...`);
      const rawProducts = await fetchProductsForPartner(partner.id, 6);
      log(`Received ${rawProducts.length} items for ${partner.name}.`);

      if (rawProducts.length > 0) {
        catalog[partner.slug] = rawProducts.map((p, idx) => {
          const currencySymbol = p.price?.currency === 'USD' ? '$' : (p.price?.currency || '$');
          const cleanPrice = p.price?.amount ? `${currencySymbol}${parseFloat(p.price.amount).toFixed(2)}` : '$0.00';
          
          // Generate uniform deep tracking link via CJ
          const deepLink = `https://www.jdoqocy.com/click-${WEBSITE_ID}-17157504?url=${encodeURIComponent(p.link)}`;

          return {
            id: p.id || `prod_${partner.slug}_${idx}`,
            storeSlug: partner.slug,
            title: p.title ? p.title.replace(/"/g, "'").slice(0, 90) : `${partner.name} Product`,
            description: cleanDescription(p.description),
            price: cleanPrice,
            currency: p.price?.currency || 'USD',
            imageUrl: p.imageLink || 'https://images.unsplash.com/photo-1526170375885-4d8ecf77b99f?auto=format&fit=crop&w=400&q=80',
            productUrl: deepLink,
            badge: idx === 0 ? partner.defaultBadge : (idx === 1 ? 'Popular' : 'Verified Stock')
          };
        });
      }
    } catch (err) {
      log(`Error querying ${partner.name}: ${err.message}`);
    }
  }

  // Generate TypeScript code
  const code = `// Auto-generated by autonomous_product_sync.cjs (Strict Zero Demo Data Rule)
// Generated at: ${new Date().toISOString()}

export interface StoreProduct {
  id: string;
  storeSlug: string;
  title: string;
  description: string;
  price: string;
  currency: string;
  imageUrl: string;
  productUrl: string;
  badge?: string;
}

export const STORE_PRODUCTS: Record<string, StoreProduct[]> = ${JSON.stringify(catalog, null, 2)};
`;

  // Compare with existing file
  let existingCode = '';
  try {
    existingCode = fs.readFileSync(PRODUCTS_FILE, 'utf8');
  } catch {}

  if (existingCode.trim() !== code.trim()) {
    log('Products updated. Saving changes to productsData.ts...');
    fs.writeFileSync(PRODUCTS_FILE, code, 'utf8');
    log('Triggering Deals Portal build...');
    try {
      execSync('cd /var/www/affiliate/deals-portal && npm run build', { stdio: 'inherit' });
      log('Deals Portal successfully rebuilt with fresh product catalog.');
    } catch (buildErr) {
      log(`Build error: ${buildErr.message}`);
    }
  } else {
    log('No changes detected in product feeds. Skipping build.');
  }
}

